"""Manual measurement boundaries; benchmark remains a separate approved command."""
import datetime
import hashlib
import json
from pathlib import Path
import re
import shlex
import subprocess
import sys
from metrics import Metrics


def now():return datetime.datetime.now(datetime.timezone.utc).isoformat()


def remote(source,args):
    code=Path(__file__).with_name(source).read_text()
    cmd='sudo -n python3 -c '+shlex.quote(code)+' '+shlex.join(args)
    result=subprocess.run(['ssh','-o','BatchMode=yes','-o','StrictHostKeyChecking=yes','-o','ConnectTimeout=10','isucon-target',cmd],capture_output=True)
    if result.returncode:raise RuntimeError('measurement remote operation failed; inspect remote state')
    return json.loads(result.stdout)


def fetch(remote_path,destination):
    # Paths are generated by fixed helpers, and verified before sending to shell.
    if not re.fullmatch(r'/var/log/(nginx|mysql)/measurements/[A-Za-z0-9_-]+/measurement/(isucon-access\.json|error\.log|slow\.log)',remote_path):
        raise ValueError('unexpected remote log path')
    with destination.open('wb') as output:
        result=subprocess.run(['ssh','-o','BatchMode=yes','-o','StrictHostKeyChecking=yes','-o','ConnectTimeout=10','isucon-target','sudo -n cat '+shlex.quote(remote_path)],stdout=output,stderr=subprocess.PIPE)
    if result.returncode:raise RuntimeError('log transfer failed')


def main():
    ident,prep=sys.argv[1:]
    if not all(re.fullmatch(r'[A-Za-z0-9][A-Za-z0-9_-]{0,63}',v) for v in [ident,prep]) or ident==prep:
        raise ValueError('invalid IDs')
    root=Path(__file__).resolve().parents[2];folder=root.parent/'artifacts'/ident
    folder.mkdir(mode=0o700)
    state=dict(run_id=ident,preparation_id=prep,status='starting',started_utc=now(),benchmark_status='unknown')
    metrics=None
    try:
        check=remote('slowlog_remote.py',[ident,'check','manual',prep])
        expected={n:hashlib.sha256((root/'infra/measurement'/n).read_bytes()).hexdigest() for n in ['nginx.conf']}
        expected['isucon-measurement-log-format.conf']=hashlib.sha256((root/'infra/measurement/nginx-log-format.conf').read_bytes()).hexdigest()
        if check['nginx_hashes']!=expected:raise RuntimeError('nginx configuration differs from prepared candidate')
        before_access=remote('nginx_log_remote.py',[ident,'before'])
        before_sql=remote('slowlog_remote.py',[ident,'rotate-before','manual',prep])
        state.update(before=check,before_access=before_access,before_sql=before_sql)
        metrics=Metrics('isucon-target',folder);metrics.start()
        state.update(status='ready',ready_utc=now())
        (folder/'metadata.json').write_text(json.dumps(state,indent=2))
        print('READY: start the separately approved benchmark. Press Enter only after its result is final.',flush=True)
        # Keep the foreground terminal alive. EOF is an interruption, not completion.
        answer=sys.stdin.readline()
        if answer=='':raise RuntimeError('EOF before completion; inspect external benchmark and log state')
        after=remote('slowlog_remote.py',[ident,'check','manual',prep])
        keys=['app_main_pid','middleware_pids','settings','nginx_hashes']
        if any(check[k]!=after[k] for k in keys):raise RuntimeError('measurement conditions changed')
        metrics_ok=metrics.stop()
        metrics=None
        if not metrics_ok:raise RuntimeError('OS collectors did not finish cleanly')
        access=remote('nginx_log_remote.py',[ident,'measurement'])
        sql=remote('slowlog_remote.py',[ident,'rotate-measurement','manual',prep])
        if any(check[k]!=sql['state'][k] for k in keys):raise RuntimeError('conditions changed during final log boundary')
        (folder/'logs').mkdir();(folder/'sql').mkdir()
        for name,path in access['files'].items():
            destination=folder/'logs'/('nginx-access.log' if name=='isucon-access.json' else 'nginx-error.log')
            fetch(path,destination)
        slow=folder/'sql/slow.log';fetch(sql['log']['path'],slow)
        if slow.stat().st_size!=sql['log']['bytes'] or hashlib.sha256(slow.read_bytes()).hexdigest()!=sql['log']['sha256']:
            raise RuntimeError('slow-log transfer digest mismatch')
        (folder/'sql/metadata.json').write_text(json.dumps(dict(status='collected',log=sql['log']),indent=2))
        # nginx fds were closed before transfer. Store local hashes for provenance.
        state.update(status='collected',after=after,access=access,sql=sql,
                     access_log_sha256=hashlib.sha256((folder/'logs/nginx-access.log').read_bytes()).hexdigest())
    except (Exception,KeyboardInterrupt) as error:
        state.update(status='interrupted-or-failed',error_type=type(error).__name__)
        print('Collection stopped. No automatic benchmark retry, final log rotation or configuration restore.',file=sys.stderr)
    finally:
        if metrics is not None:
            try:state['metrics_stop_success']=metrics.stop()
            except Exception:state['metrics_stop_success']=False
        state['finished_utc']=now()
        (folder/'metadata.json').write_text(json.dumps(state,indent=2))
        (folder/'benchmark-result.json').write_text(json.dumps(dict(run_id=None,pass_status=None,score=None,result_path=None),indent=2))
    print('Collection '+state['status']+': '+str(folder))
    return 0 if state['status']=='collected' else 1


if __name__=='__main__':sys.exit(main())
